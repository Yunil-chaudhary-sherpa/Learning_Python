'''Looping through all key-value pairs-
Using loop helps user to output every key stored in a dictionary using for loop.
'''
char = {
  'username':'Arcks'
  ,'age':'21'
  ,'speed':'90'
  ,'shooting':'83'
  ,'passing':'74'
  }
for key, value in char.items():
  print("\nkey:"+key)
  print("value:"+value)
# For loop in dictionary , you create names for the variable tha will hold the key and value in each key-value pair.

 